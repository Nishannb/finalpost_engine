/**
 * Writes the two baseline manifests. No model call, no network.
 *   node --experimental-strip-types src/eval/baselineCli.ts            (npm run eval:baseline)
 * Output: server/src/eval/baselines/{legacy,experimental}.manifest.json  (+ a summary under remotion/out/phase13-eval/)
 * Refuses to overwrite an existing manifest unless EVAL_BASELINE_OVERWRITE=1 (a baseline is frozen on purpose).
 */
import {existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

import {env} from '../config/env.ts';
import {classify, codeState, indexArtifacts, sha256File} from './baseline.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..', '..');
const outDir = join(here, 'baselines');
mkdirSync(outDir, {recursive: true});

const writeFrozen = (name: string, data: unknown) => {
  const path = join(outDir, name);
  if (existsSync(path) && process.env.EVAL_BASELINE_OVERWRITE !== '1') {
    console.log(`kept existing ${name} (set EVAL_BASELINE_OVERWRITE=1 to replace)`);
    return;
  }
  writeFileSync(path, JSON.stringify(data, null, 1));
  console.log(`wrote ${name}`);
};

const filesIn = (dir: string, ext: string) => readdirSync(join(here, dir)).filter(name => name.endsWith(ext)).sort().map(name => ({path: `server/src/eval/${dir}/${name}`, sha256: sha256File(join(here, dir, name))}));

const flags = {
  GENERATED_TRANSITIONS_ENABLED: env.GENERATED_TRANSITIONS_ENABLED,
  DIRECTOR_V2: env.DIRECTOR_V2,
  NORTH_STAR: env.NORTH_STAR,
  MOTION_GRAPHICS_ENABLED: env.MOTION_GRAPHICS_ENABLED,
  CONTENT_PROFILE_ENABLED: env.CONTENT_PROFILE_ENABLED,
  PIPELINE_MODE: env.PIPELINE_MODE,
  ZOOM_SCALE: env.ZOOM_SCALE,
  VISUAL_CONTEXT_V2: (env as unknown as {VISUAL_CONTEXT_V2?: boolean}).VISUAL_CONTEXT_V2 ?? false,
};

const state = codeState(root);
const fixtures = filesIn('fixtures', '.json').map(file => {
  const data = JSON.parse(readFileSync(join(root, file.path), 'utf8'));
  return {...file, id: data.id, kind: data.kind, source: data.provenance?.directorDump, sourceSha256: data.provenance?.directorDumpSha256};
});

writeFrozen('legacy.manifest.json', {
  kind: 'legacy_compatibility_baseline',
  definition: 'The working state approved at the start of Phase 13 (Phases 8–12 uncommitted work included), plus three harness-driven planner/schema fixes listed under `changesSinceStartOfPhase13`, with every experimental flag off.',
  generatedBy: 'server/src/eval/baselineCli.ts',
  codeState: state,
  flags,
  nodeVersion: process.version,
  fixtures,
  goldens: filesIn('golden', '.json'),
  changesSinceStartOfPhase13: [
    'brollPlanner.finishRemap: per-kind cap keeps the EARLIEST edits instead of the first N in array order (M3 determinism)',
    'editConflicts.ledgerIdResolver: matches a moved edit by its FINAL span, so the Director\'s ledger entry reaches the renderer instead of a duplicate being created (M6)',
    'remotion blueprintSchema: inset transitionIn/Out accept 0.25–1.2 s, the range the planner and renderer already use (M1)',
  ],
  preFixPlannerOutputs: 'remotion/out/phase13-eval/prefix-goldens/ (planner goldens as they were before those three changes; differences are ledger ids for moved cutaways, an inset reveal id, and the emphasis cap in the Hi case)',
  referenceOutputs: [
    'remotion/out/phase7-content-profile/hi/blueprint.json',
    'remotion/out/phase6-sonnet/full-edits/blueprint.json',
    'remotion/out/phase5-e2e/blueprint.json',
  ].filter(path => existsSync(join(root, path))).map(path => ({path, sha256: sha256File(join(root, path)), role: 'earlier_pipeline_output_reference_only'})),
  limitations: [
    'Goldens are SELF-GENERATED by replaying saved responses through the current code. They pin behaviour; they are not independently verified correct output.',
    'No genuinely approved legacy PIPELINE output (end-to-end blueprint or render) from the current code exists: earlier real outputs were produced by earlier code, and planner behaviour changed on purpose in Phases 8–10B, so they cannot serve as goldens.',
    'The corpus is 8 distinct saved v1 responses over 2 source clips (three-things, hi-relationship); content diversity is limited.',
    'There is no real v2 Director response in the repo, so v2 has no legacy baseline.',
    'Code identity is treeSha256 over behaviour-defining files; HEAD is not sufficient because the tree is uncommitted.',
  ],
});

const phaseDirs = ['remotion/out/phase9-validation', 'remotion/out/phase10b-validation', 'remotion/out/phase11-validation', 'remotion/out/phase12-design', 'server/src/eval/fixtures', 'server/src/stages/broll/__fixtures__'];
const {entries, unclassified} = indexArtifacts(root, phaseDirs);
const earlier = indexArtifacts(root, ['remotion/out/phase5-e2e', 'remotion/out/phase6-sonnet', 'remotion/out/phase7-content-profile']).entries.filter(entry => /01-gemini-director\.json$|blueprint\.json$/.test(entry.path));
const tests = ['server/src/stages/broll/deterministicReplay.test.ts', 'server/src/stages/broll/planBRoll.ledger.test.ts', 'server/src/stages/broll/editExecutionContracts.test.ts', 'server/src/stages/broll/transitionRender.test.ts', 'server/src/stages/filters/autoZoom.test.ts', 'server/src/eval/harness.test.ts'].map(path => ({path, sha256: sha256File(join(root, path)), cls: classify(path)?.cls ?? 'test_source', stages: classify(path)?.stages ?? ['none'], limits: classify(path)?.limits ?? ''}));
const byClass: Record<string, number> = {};
for (const entry of [...entries, ...earlier, ...tests]) {
  byClass[entry.cls] = (byClass[entry.cls] ?? 0) + 1;
}
writeFrozen('experimental.manifest.json', {
  kind: 'experimental_capability_baseline',
  generatedBy: 'server/src/eval/baselineCli.ts',
  codeState: state,
  flags,
  classes: {
    saved_response_replay_fixture: 'a real Director response saved earlier and replayed offline',
    synthetic_fixture: 'inputs written by hand/test code; no real model output',
    hand_built_blueprint_render: 'a blueprint written by hand and rendered locally; renderer-only evidence',
    earlier_pipeline_output: 'an output of an earlier phase\'s real pipeline run; reference only',
    saved_response_replay_render: 'a saved response replayed through code and rendered locally',
    design_document: 'prose',
    test_source: 'test code',
  },
  countsByClass: byClass,
  unclassifiedFiles: unclassified,
  artifacts: [...entries, ...earlier, ...tests],
  note: 'Existing evidence is hashed in place and never modified or moved.',
});
